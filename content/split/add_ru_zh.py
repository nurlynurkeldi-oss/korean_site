    audit_korean(new, 'L%02d' % lid)
    path = os.path.join(SPLIT, 'L%02d.json' % lid)
    with io.open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(json.dumps(new, ensure_ascii=False, indent=2) + '\n')
    print('wrote', path, 'added fields:', leaves(new) - leaves(ORIG[lid]))
