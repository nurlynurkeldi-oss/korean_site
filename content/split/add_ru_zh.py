def rep(src, pairs, label=''):
    """Apply (old, new) replacements to src; assert each old is found."""
    out = src
    for old, new in pairs:
        if old not in out:
            raise AssertionError('replacement not found in %s: %r' % (label or src[:40], old))
        out = out.replace(old, new)
    return out


def rx(s, pat, label=''):
    m = re.search(pat, s)
    if not m:
        raise AssertionError('regex not found in %s: %s' % (label or s[:40], pat))
    return m.group(1) if m.groups() else m.group(0)


