def verify(orig, new):
    def walk(o, n, path):
        if isinstance(o, dict):
            for k, v in o.items():
                if k not in n:
                    raise ValueError('missing key at %s: %s' % (path, k))
                if isinstance(v, (dict, list)):
                    walk(v, n[k], path + '.' + k)
                elif v != n[k]:
                    raise ValueError('value changed at %s.%s' % (path, k))
        elif isinstance(o, list):
            if len(o) != len(n):
                raise ValueError('list length changed at %s' % path)
            for i, (a, b) in enumerate(zip(o, n)):
                walk(a, b, '%s[%d]' % (path, i))
    walk(orig, new, '$')

    PRED = {
        'skillsRu': 'skillsKk', 'skillsZh': 'skillsRu',
        'nameRu': 'nameKk', 'nameZh': 'nameRu',
        'descRu': 'descKk', 'descZh': 'descRu',
        'ruleRu': 'ruleKk', 'ruleZh': 'ruleRu',
        'titleRu': 'titleKk', 'titleZh': 'titleRu',
        'cultureRu': 'cultureKk', 'cultureZh': 'cultureRu',
        'qZh': 'qRu',
        'optionsRu': 'options', 'optionsZh': 'optionsRu',
        'exRu': 'exKk', 'exZh': 'exRu',
    }
    def order(d, kind, path):
        keys = list(d.keys())
        for k, v in d.items():
            ok = True
            if kind == 'vocab' and k == 'zh':
                ok = keys[keys.index(k) - 1] == 'ru'
            elif kind in ('example', 'line') and k == 'ru':
                ok = keys[keys.index(k) - 1] == 'kk'
            elif kind in ('example', 'line') and k == 'zh':
                ok = keys[keys.index(k) - 1] == 'ru'
            elif kind == 'test' and k == 'qRu':
                ok = keys[keys.index(k) - 1] == ('qKo' if 'qKo' in d else 'qKk')
            elif k in PRED:
                ok = keys[keys.index(k) - 1] == PRED[k]
            if not ok:
                raise ValueError('bad position of %s at %s' % (k, path))
            if isinstance(v, dict):
                order(v, 'sub', path + '.' + k)
    order(new, 'lesson', '$')
    for i, w in enumerate(new['vocabulary']):
        order(w, 'vocab', '$.vocabulary[%d]' % i)
    for i, g in enumerate(new['grammar']):
        order(g, 'grammar', '$.grammar[%d]' % i)
        for j, e in enumerate(g['examples']):
            order(e, 'example', '$.grammar[%d].examples[%d]' % (i, j))
    order(new['dialogue'], 'dialogue', '$.dialogue')
    for i, l in enumerate(new['dialogue']['lines']):
        order(l, 'line', '$.dialogue.lines[%d]' % i)
    for i, t in enumerate(new['tests']):
        order(t, 'test', '$.tests[%d]' % i)

    NEW_KEYS = {'skillsRu', 'skillsZh', 'zh', 'nameRu', 'nameZh', 'descRu', 'descZh',
                'ruleRu', 'ruleZh', 'ru', 'titleRu', 'titleZh', 'cultureRu', 'cultureZh',
                'qRu', 'qZh', 'optionsRu', 'optionsZh', 'exRu', 'exZh'}
    def count_new(d, orig_d, n):
        if isinstance(d, dict):
            for k in d:
                if k not in orig_d:
                    assert k in NEW_KEYS, 'unexpected new key %s' % k
                    n[0] += 1
                if k in orig_d:
                    count_new(d[k], orig_d[k], n)
        else:
            for a, b in zip(d, orig_d):
                count_new(a, b, n)
    n = [0]
    count_new(new, orig, n)
    return n[0]

