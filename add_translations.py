def load_mono(fname, lid):
    for l in json.load(io.open(base + '\\' + fname, encoding='utf-8')):
        if l['id'] == lid:
            return l
    raise ValueError('lesson %s not found in %s' % (lid, fname))

def between(s, pre, suf, maxtok=3):
    """1..maxtok токенов между казахскими якорями pre и suf"""
    pat = re.escape(pre) + r' (\S+(?: \S+){0,%d}) ' % (maxtok - 1) + re.escape(suf)
    m = re.search(pat, s)
    if not m:
        raise ValueError('no between %r/%r in %r' % (pre, suf, s))
    return m.group(1)

def begin(s, suf, maxtok=1):
    """1..maxtok токенов в начале строки до якоря suf"""
    pat = r'^(\S+(?: \S+){0,%d}) ' % (maxtok - 1) + re.escape(suf)
    m = re.search(pat, s)
    if not m:
        raise ValueError('no begin %r in %r' % (suf, s))
    return m.group(1)

def end(s, pre):
    pat = re.escape(pre) + r' (.*)$'
    m = re.search(pat, s)
    if not m:
        raise ValueError('no end %r in %r' % (pre, s))
    return m.group(1)

def add_after(d, anchor, additions):
    out = {}
    done = False
    for k, v in d.items():
        out[k] = v
        if k == anchor and not done:
            for nk, nv in additions:
                out[nk] = nv
            done = True
    if not done:
        raise ValueError('anchor not found: ' + anchor)
    return out

def build_lesson(orig, tr):
    d = copy.deepcopy(orig)
    d = add_after(d, 'skillsKk', [('skillsRu', tr['skillsRu']), ('skillsZh', tr['skillsZh'])])
    if len(tr['vocabZh']) != len(d['vocabulary']):
        raise ValueError('vocab length mismatch: %d vs %d' % (len(tr['vocabZh']), len(d['vocabulary'])))
    d['vocabulary'] = [add_after(w, 'ru', [('zh', z)]) for w, z in zip(d['vocabulary'], tr['vocabZh'])]
    if len(tr['grammar']) != len(d['grammar']):
        raise ValueError('grammar length mismatch')
    newg = []
    for g, gt in zip(d['grammar'], tr['grammar']):
        g = add_after(g, 'nameKk', [('nameRu', gt['nameRu']), ('nameZh', gt['nameZh'])])
        g = add_after(g, 'descKk', [('descRu', gt['descRu']), ('descZh', gt['descZh'])])
        g = add_after(g, 'ruleKk', [('ruleRu', gt['ruleRu']), ('ruleZh', gt['ruleZh'])])
        if len(gt['exRu']) != len(g['examples']) or len(gt['exZh']) != len(g['examples']):
            raise ValueError('examples length mismatch')
        g['examples'] = [add_after(e, 'kk', [('ru', r), ('zh', z)]) for e, r, z in zip(g['examples'], gt['exRu'], gt['exZh'])]
        newg.append(g)
    d['grammar'] = newg
    dlg = add_after(d['dialogue'], 'titleKk', [('titleRu', tr['dlgTitleRu']), ('titleZh', tr['dlgTitleZh'])])
    if len(tr['linesRu']) != len(dlg['lines']) or len(tr['linesZh']) != len(dlg['lines']):
        raise ValueError('lines length mismatch')
    dlg['lines'] = [add_after(l, 'kk', [('ru', r), ('zh', z)]) for l, r, z in zip(dlg['lines'], tr['linesRu'], tr['linesZh'])]
    d['dialogue'] = dlg
    d = add_after(d, 'cultureKk', [('cultureRu', tr['cultureRu']), ('cultureZh', tr['cultureZh'])])
    if len(tr['tests']) != len(d['tests']):
        raise ValueError('tests length mismatch')
    newt = []
    for t, tt in zip(d['tests'], tr['tests']):
        anchor_q = 'qKo' if 'qKo' in t else 'qKk'
        t = add_after(t, anchor_q, [('qRu', tt['qRu']), ('qZh', tt['qZh'])])
        t = add_after(t, 'options', [('optionsRu', tt['optionsRu']), ('optionsZh', tt['optionsZh'])])
        t = add_after(t, 'exKk', [('exRu', tt['exRu']), ('exZh', tt['exZh'])])
        newt.append(t)
    d['tests'] = newt
    return d

